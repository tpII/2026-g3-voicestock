"""One validated operation waiting for the operator to confirm it.

Creating this object does not change stock. The flow keeps the only copy.
"""

import uuid
from dataclasses import dataclass

from pi.operation_contract import ValidatedOperation
from pi.pending_operation.view import PendingOperationView

_OPERATION_LABELS = {
    "add_stock": "agregar",
    "remove_stock": "quitar",
}
_CONFIRMATION_VERBS = {
    "add_stock": "Agregar",
    "remove_stock": "Quitar",
}


@dataclass(frozen=True, slots=True)
class PendingOperation:
    """A validated operation that still needs confirmation.

    ``operation_id`` is generated by the application. ``recognized_text`` is
    the text that led to the operation, when the PC sent it. The validated
    operation is the only inventory request this object carries.
    """

    operation_id: str
    recognized_text: str
    validated_operation: ValidatedOperation

    def __post_init__(self) -> None:
        if not isinstance(self.operation_id, str) or not self.operation_id.strip():
            raise ValueError("operation_id must be a non-blank string")
        if not isinstance(self.recognized_text, str):
            raise TypeError("recognized_text must be a string")
        if not isinstance(self.validated_operation, ValidatedOperation):
            raise TypeError("validated_operation must be a ValidatedOperation")

    @classmethod
    def from_validated(
        cls,
        validated_operation: ValidatedOperation,
        recognized_text: str,
        operation_id: str | None = None,
    ) -> "PendingOperation":
        """Build a pending operation from a value the validator already accepted."""
        return cls(
            operation_id=operation_id or str(uuid.uuid4()),
            recognized_text=recognized_text,
            validated_operation=validated_operation,
        )

    def to_view(self) -> PendingOperationView:
        """Public snapshot the web already renders. Not a second stored copy."""
        validated = self.validated_operation
        unit = "unidad" if validated.unit == "unit" else validated.unit
        return PendingOperationView(
            operation_id=self.operation_id,
            recognized_text=self.recognized_text,
            product=validated.product_name,
            operation=_OPERATION_LABELS.get(validated.operation, validated.operation),
            quantity=validated.quantity,
            unit=unit,
            confirmation_message=_confirmation_message(validated, unit),
        )


def _confirmation_message(validated: ValidatedOperation, unit: str) -> str:
    verb = _CONFIRMATION_VERBS.get(validated.operation, validated.operation)
    if validated.unit == "unit" and validated.quantity != 1:
        unit = "unidades"
    return f"{verb} {validated.quantity} {unit} de {validated.product_name}"
